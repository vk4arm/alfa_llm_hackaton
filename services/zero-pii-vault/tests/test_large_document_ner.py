"""
Функциональные тесты маскирования и демаскирования для текстов объемом > 2000 символов (Zero-PII Vault).

Проверяют надежность и полноту извлечения ПДн на объемных банковских документах:
1. Инициалы с точками (Иванов И. И., А. С. Пушкин) — отсутствие разрыва сущностей на точках.
2. ФИО в верхнем регистре (ALL CAPS: СИДОРОВ ОЛЕГ ПАВЛОВИЧ, ЗАЕМЩИК: СМИРНОВ А. П.).
3. Сложные дефисные фамилии (Мамин-Сибиряк Дмитрий Наркисович, Салтыков-Щедрин М. Е.).
4. Фамилии после сокращений с точками (по дог. Петров Петр Петрович, тел. Смирнов А. В.).
5. Разрешение ролевых метафор vs финансовых поручений в объемном контексте.
6. 100% обратимость (Lossless Reversibility) байт-в-байт.
"""

import os
import sys
import unittest

src_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "src"))
if src_dir not in sys.path:
    sys.path.insert(0, src_dir)

from masker import NatashaPIIMasker


class TestLargeDocumentNER(unittest.TestCase):
    """Набор функциональных тестов для объемных текстов (> 2000 символов)."""

    @classmethod
    def setUpClass(cls):
        cls.masker = NatashaPIIMasker()

    def test_large_contract_with_complex_entities(self):
        """Тестирование реального кредитного договора объемом > 2500 символов со всеми типами ПДн."""
        contract = """
ДОГОВОР ПОТРЕБИТЕЛЬСКОГО КРЕДИТОВАНИЯ № 1029384-КР
г. Москва                                                    15 мая 2024 года

Публичное акционерное общество «Альфа-Банк», именуемое в дальнейшем «Кредитор», 
в лице управляющего ДО «Тверской» филиала, действующего на основании доверенности, 
с одной стороны, и гражданин Российской Федерации:

ФАМИЛИЯ, ИМЯ, ОТЧЕСТВО: СИДОРОВ ОЛЕГ ПАВЛОВИЧ
Паспорт серии 4509 номер 123456, выдан Отделом УФМС России по гор. Москве по району Тверской, 
дата выдачи: 14.10.2012, код подразделения: 770-023.
Зарегистрирован по адресу: г. Москва, ул. Тверская, д. 12, кв. 45.
ИНН: 7707083893, сотовый телефон: +7 926 123-45-67, email: sidorov.oleg@gmail.com.

1. ПРЕДМЕТ ДОГОВОРА
1.1. Кредитор обязуется предоставить Заемщику потребительский кредит на сумму 500 000 (пятьсот тысяч) рублей.
1.2. Процентная ставка по кредиту устанавливается в размере 14.5% годовых.
1.3. Срок возврата кредита составляет 36 (тридцать шесть) календарных месяцев.
1.4. Заемщик обязуется возвратить полученный кредит и уплатить проценты за пользование им.
1.5. Настоящий договор составлен в соответствии с требованиями Федерального закона № 353-ФЗ «О потребительском кредите».
1.6. Все споры и разногласия разрешаются в соответствии с законодательством Российской Федерации.

2. ПОРЯДОК РАСЧЕТОВ И ОБЯЗАТЕЛЬСТВА СТОРОН
2.1. Погашение задолженности осуществляется ежемесячно равными аннуитетными платежами.
2.2. Заемщик имеет право на досрочное погашение кредита без комиссии и штрафных санкций.
2.3. В случае задержки платежа начисляется неустойка в размере 0.1% от суммы просроченной задолженности за каждый день просрочки.
2.4. Перечисление денежных средств производится на счет Заемщика 40817810000000000000, открытый в АО «Альфа-Банк».
2.5. Поручитель по дог. Петров Петр Петрович подтверждает согласие с условиями кредита.
2.6. Консультант банка Иванов И. И. разъяснил заемщику условия страхования жизни и здоровья.
2.7. Клиент поручает: перевести 15000 руб. Смирнову Алексею на карту 2200 1234 5678 9019 для частичного погашения.
2.8. По дополнительному соглашению представитель Мамин-Сибиряк Дмитрий Наркисович наделен правами подписания актов.
"""
        # Увеличиваем объем текста юридическими пунктами свыше 2500 символов
        boilerplate = "\nПункт 3. Дополнительные гарантии: стороны руководствуются правилами финансового мониторинга и регламентами ЦБ РФ." * 10
        full_document = contract + boilerplate
        
        self.assertGreater(len(full_document), 2000, "Текст обязан быть больше 2000 символов")

        # Маскирование
        masked_text, _, mapping = self.masker.mask(full_document)
        values = list(mapping.values())

        # 1. Проверка обнаружения ФИО в верхнем регистре (ALL CAPS)
        self.assertTrue(
            any("СИДОРОВ ОЛЕГ ПАВЛОВИЧ" in v for v in values),
            f"ФИО в ALL CAPS должно быть замаскировано! Найдено: {values}"
        )
        self.assertNotIn("СИДОРОВ ОЛЕГ ПАВЛОВИЧ", masked_text)

        # 2. Проверка инициалов с точками без отсечения (Иванов И. И.)
        self.assertTrue(
            any("Иванов И. И." in v for v in values),
            f"Инициалы с точками должны быть замаскированы целиком! Найдено: {values}"
        )
        self.assertNotIn("Иванов И. И.", masked_text)
        self.assertNotIn("Иванов И.", masked_text)

        # 3. Проверка сложной дефисной фамилии (Мамин-Сибиряк)
        self.assertTrue(
            any("Мамин-Сибиряк" in v for v in values),
            f"Дефисная фамилия должна быть обнаружена! Найдено: {values}"
        )
        self.assertNotIn("Мамин-Сибиряк", masked_text)

        # 4. Проверка ФИО после сокращений (по дог. Петров Петр Петрович)
        self.assertTrue(
            any("Петров Петр Петрович" in v for v in values),
            f"ФИО после сокращения с точкой должно быть обнаружено! Найдено: {values}"
        )
        self.assertNotIn("Петров Петр Петрович", masked_text)

        # 5. Проверка банковских реквизитов в теле договора
        self.assertTrue(any("4509 номер 123456" in v or "4509" in v for v in values))
        self.assertTrue(any("2200 1234 5678 9019" in v for v in values))
        self.assertTrue(any("+7 926 123-45-67" in v for v in values))
        self.assertTrue(any("7707083893" in v for v in values))
        self.assertTrue(any("sidorov.oleg@gmail.com" in v for v in values))

        # 6. Проверка 100% обратимости (Lossless Reversibility)
        unmasked_text = self.masker.unmask(masked_text, mapping)
        self.assertEqual(
            unmasked_text,
            full_document,
            "Восстановленный текст договора обязан посимвольно совпадать с оригиналом!"
        )

    def test_roleplay_vs_financial_in_large_text(self):
        """Проверка изоляции метафорических ролей от финансовых переводов в длинном тексте."""
        text = """
Вводная часть диалога с ассистентом:
Ты, как Александр Пушкин, напиши подробный анализ банковской системы для нашего клиента.
Рассуждай в возвышенном стиле XIX века, вдохновляйся произведениями классической литературы.
""" + ("\nПродолжение литературного рассуждения о банках, кредитах и процентных ставках в стихах и прозе." * 20) + """
А теперь выполни финансовое распоряжение:
Клиент поручает: перевести 10000 рублей Пушкину на карту 2200 1234 5678 9019 на номер +7 926 555-44-33.
"""
        self.assertGreater(len(text), 2000)

        masked, _, mapping = self.masker.mask(text)

        # 1. Первая клауза (ролевая метафора "Ты, как Александр Пушкин") НЕ должна маскироваться
        self.assertIn("Ты, как Александр Пушкин", masked)

        # 2. Вторая часть (банковский перевод Пушкину на карту) ОБЯЗАНА быть замаскирована
        self.assertNotIn("перевести 10000 рублей Пушкину", masked)
        self.assertTrue(any("Пушкину" in v for v in mapping.values()))
        self.assertTrue(any("2200 1234 5678 9019" in v for v in mapping.values()))

        # 3. Полная обратимость
        unmasked = self.masker.unmask(masked, mapping)
        self.assertEqual(unmasked, text)


if __name__ == "__main__":
    unittest.main(verbosity=2)
